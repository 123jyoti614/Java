package com.google.day_15.constructors;

public class Product {


	String name;
	int price;
	String productId;
	String brandName;
	public Product(String _name, int _price, String _productId, String _brandName) {
		
		this.name = _name;
		this.price = _price;
		this.productId = _productId;
		this.brandName = _brandName;
	}
	
}
